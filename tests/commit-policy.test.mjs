// The script inside .github/workflows/commit-policy.yml, run as written there with the
// workflow's default inputs. Each case builds a throwaway repository with one new commit.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const WORKFLOW = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../.github/workflows/commit-policy.yml'), 'utf8')
  .replace(/\r\n/g, '\n');

/** The `run: |` block of the step with `id: policy`, dedented. */
function policyScript(text) {
  const lines = text.split('\n');
  const id = lines.findIndex((l) => /^\s+id: policy\s*$/.test(l));
  assert.ok(id > 0, 'commit-policy.yml has a step with id: policy');
  const run = lines.findIndex((l, i) => i > id && /^\s+run: \|\s*$/.test(l));
  const body = [];
  const base = lines[run].match(/^ */)[0].length;
  for (let i = run + 1; i < lines.length && (lines[i].trim() === '' || lines[i].match(/^ */)[0].length > base); i++) body.push(lines[i]);
  const cut = Math.min(...body.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  return body.map((l) => l.slice(cut)).join('\n');
}

/** The default of one workflow_call input. */
function inputDefault(name) {
  const m = WORKFLOW.match(new RegExp(`\\n {6}${name}:\\n(?: {8}.*\\n)*? {8}default: (.*)\\n`));
  assert.ok(m, `input ${name} has a default`);
  return m[1].trim().replace(/^'(.*)'$/, '$1');
}

const SCRIPT = policyScript(WORKFLOW);
const PACO = { name: 'Paco Cartones', email: '253313177+pacocartones@users.noreply.github.com' };

function run({ name, email, message = 'change', branch, headRepo = 'pacocartones/repo', prAuthor = 'someone', pr = true }) {
  const dir = mkdtempSync(join(tmpdir(), 'commit-policy-'));
  try {
    const git = (args, env = {}) => execFileSync('git', args, { cwd: dir, env: { ...process.env, ...env }, encoding: 'utf8' }).trim();
    git(['init', '-q']);
    git(['-c', 'user.name=base', '-c', 'user.email=base@example.com', '-c', 'commit.gpgsign=false', 'commit', '-q', '--allow-empty', '-m', 'base']);
    const base = git(['rev-parse', 'HEAD']);
    git(['-c', 'commit.gpgsign=false', 'commit', '-q', '--allow-empty', '-m', message], {
      GIT_AUTHOR_NAME: name, GIT_AUTHOR_EMAIL: email, GIT_COMMITTER_NAME: name, GIT_COMMITTER_EMAIL: email,
    });
    const head = git(['rev-parse', 'HEAD']);
    const event = join(dir, 'event.json');
    writeFileSync(event, JSON.stringify({ pull_request: { head: { repo: { full_name: headRepo } }, user: { login: prAuthor } } }));
    const script = join(dir, 'policy.sh');
    writeFileSync(script, SCRIPT);
    const res = spawnSync('bash', [script], {
      cwd: dir,
      encoding: 'utf8',
      env: {
        ...process.env,
        BASE_SHA: pr ? base : '',
        HEAD_SHA: pr ? head : '',
        MAINTAINER_NAME: inputDefault('maintainer-name'),
        MAINTAINER_EMAIL: inputDefault('maintainer-email'),
        MAINTAINER_LOGIN: inputDefault('maintainer-login'),
        BRANCH_PATTERN: inputDefault('branch-pattern'),
        GITHUB_HEAD_REF: branch ?? '',
        GITHUB_EVENT_PATH: branch ? event : '',
        GITHUB_REPOSITORY: 'pacocartones/repo',
      },
    });
    return { code: res.status, out: res.stdout + res.stderr };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test('the inputs default to the maintainer identity and the branch naming rule', () => {
  assert.equal(inputDefault('maintainer-name'), PACO.name);
  assert.equal(inputDefault('maintainer-email'), PACO.email);
  assert.equal(inputDefault('maintainer-login'), 'pacocartones');
  assert.equal(inputDefault('branch-pattern'), '^(feat|fix|docs|data|test|ci|chore|refactor)/[a-z0-9-]+$');
});

test('a clean maintainer commit passes', () => {
  const r = run({ ...PACO, message: 'feat: add a thing\n\nBody.' });
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, /commit policy: ok/);
});

test('a maintainer commit with an AI co-author trailer fails', () => {
  const r = run({ ...PACO, message: 'fix: thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>' });
  assert.equal(r.code, 1, r.out);
  assert.match(r.out, /AI attribution/);
});

test('a maintainer commit with a generated-by footer fails', () => {
  for (const footer of ['🤖 Generated with Claude Code', 'Generated by Copilot', 'Co-authored-by: Codex <codex@openai.com>']) {
    const r = run({ ...PACO, message: `docs: thing\n\n${footer}` });
    assert.equal(r.code, 1, `${footer}\n${r.out}`);
  }
});

test('the maintainer name or login with another address fails on identity', () => {
  for (const id of [{ name: 'Paco Cartones', email: 'paco@example.com' }, { name: 'pacocartones', email: PACO.email }, { name: 'Someone', email: 'pacocartones@users.noreply.github.com' }]) {
    const r = run(id);
    assert.equal(r.code, 1, `${id.name} <${id.email}>\n${r.out}`);
    assert.match(r.out, /Maintainer identity/);
  }
});

test('a contributor keeps their own identity and attribution choices', () => {
  const r = run({ name: 'Ada Contributor', email: 'ada@example.com', message: 'fix: thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>' });
  assert.equal(r.code, 0, r.out);
});

test('branch names are checked on branches of the repository itself', () => {
  assert.equal(run({ ...PACO, branch: 'feat/initial-workflows' }).code, 0);
  assert.equal(run({ ...PACO, branch: 'ci/actionlint-2' }).code, 0);
  for (const branch of ['my-branch', 'feature/x', 'feat/Upper', 'feat/', 'claude/some-task']) {
    const r = run({ ...PACO, branch });
    assert.equal(r.code, 1, `${branch}\n${r.out}`);
    assert.match(r.out, /Branch name/);
  }
});

test('fork branches and Dependabot branches are not checked for naming', () => {
  assert.equal(run({ ...PACO, branch: 'patch-1', headRepo: 'someone/repo' }).code, 0);
  assert.equal(run({ name: 'dependabot[bot]', email: '49699333+dependabot[bot]@users.noreply.github.com', branch: 'dependabot/npm_and_yarn/x-1.2.3', prAuthor: 'dependabot[bot]' }).code, 0);
});

test('outside a pull request there is nothing to check', () => {
  const r = run({ ...PACO, message: 'x\n\nCo-Authored-By: Claude <noreply@anthropic.com>', pr: false });
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, /Not a pull request event/);
});
