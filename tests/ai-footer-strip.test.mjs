// The script inside .github/workflows/ai-footer-strip.yml, run as written there. A fake `gh`
// on PATH records the API call instead of sending it, so each case shows what the workflow
// would PATCH (or that it would not call the API at all).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const WORKFLOW = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../.github/workflows/ai-footer-strip.yml'), 'utf8')
  .replace(/\r\n/g, '\n');

/** The `run: |` block of the step with `id: strip`, dedented. */
function stripScript(text) {
  const lines = text.split('\n');
  const id = lines.findIndex((l) => /^\s+id: strip\s*$/.test(l));
  assert.ok(id > 0, 'ai-footer-strip.yml has a step with id: strip');
  const run = lines.findIndex((l, i) => i > id && /^\s+run: \|\s*$/.test(l));
  const body = [];
  const base = lines[run].match(/^ */)[0].length;
  for (let i = run + 1; i < lines.length && (lines[i].trim() === '' || lines[i].match(/^ */)[0].length > base); i++) body.push(lines[i]);
  const cut = Math.min(...body.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length));
  return body.map((l) => l.slice(cut)).join('\n');
}

const SCRIPT = stripScript(WORKFLOW);

// The fake gh writes its arguments, and the JSON payload it was given with --input, to files.
const FAKE_GH = [
  '#!/bin/sh',
  'printf \'%s\\n\' "$@" > "$FAKE_DIR/args"',
  'while [ $# -gt 0 ]; do',
  '  if [ "$1" = --input ]; then if [ "$2" = - ]; then cat; else cat "$2"; fi > "$FAKE_DIR/stdin"; fi',
  '  shift',
  'done',
  '',
].join('\n');

/**
 * Run the script for one event. `body` is the text of the issue, comment or review.
 * Returns { code, out, args, payload, summary }; args and payload are null when gh was not called.
 */
function run({ event = 'issue_comment', body, author = 'pacocartones' }) {
  const dir = mkdtempSync(join(tmpdir(), 'ai-footer-'));
  try {
    const bin = join(dir, 'bin');
    mkdirSync(bin);
    writeFileSync(join(bin, 'gh'), FAKE_GH);
    chmodSync(join(bin, 'gh'), 0o755);
    const script = join(dir, 'strip.sh');
    writeFileSync(script, SCRIPT);
    const runnerTemp = join(dir, 'tmp');
    mkdirSync(runnerTemp);
    const summary = join(dir, 'summary.md');
    const env = {
      ...process.env,
      PATH: `${bin}:${process.env.PATH}`,
      FAKE_DIR: dir,
      RUNNER_TEMP: runnerTemp,
      GITHUB_STEP_SUMMARY: summary,
      GH_TOKEN: 'dummy',
      REPO: 'pacocartones/repo',
      EVENT: event,
      AUTHOR: author,
      ISSUE_BODY: '', COMMENT_BODY: '', REVIEW_BODY: '',
      ISSUE: '7', PR: '', COMMENT_ID: '', REVIEW_ID: '', URL: '',
    };
    if (event === 'issues') Object.assign(env, { ISSUE_BODY: body, URL: 'https://github.com/pacocartones/repo/issues/7' });
    if (event === 'issue_comment') Object.assign(env, { ISSUE_BODY: 'the issue itself', COMMENT_BODY: body, COMMENT_ID: '101', URL: 'https://github.com/pacocartones/repo/issues/7#issuecomment-101' });
    if (event === 'pull_request_review_comment') Object.assign(env, { ISSUE: '', PR: '8', COMMENT_BODY: body, COMMENT_ID: '202', URL: 'https://github.com/pacocartones/repo/pull/8#discussion_r202' });
    if (event === 'pull_request_review') Object.assign(env, { ISSUE: '', PR: '8', REVIEW_BODY: body, REVIEW_ID: '303', URL: 'https://github.com/pacocartones/repo/pull/8#pullrequestreview-303' });
    const res = spawnSync('bash', ['-e', script], { cwd: dir, encoding: 'utf8', env });
    const read = (f) => (existsSync(join(dir, f)) ? readFileSync(join(dir, f), 'utf8') : null);
    const stdin = read('stdin');
    return {
      code: res.status,
      out: res.stdout + res.stderr,
      args: read('args')?.trim().split('\n') ?? null,
      payload: stdin === null ? null : JSON.parse(stdin),
      summary: read('summary.md'),
    };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** The body the workflow would write back, or null when it would leave the text alone. */
const cleaned = (body, opts = {}) => {
  const r = run({ body, ...opts });
  assert.equal(r.code, 0, r.out);
  return r.payload === null ? null : r.payload.body;
};

const FOOTERS = [
  'Generated by [Claude Code](https://claude.ai/code)',
  '_Generated by [Claude Code](https://claude.ai/code)_',
  '*Generated by [Claude Code](https://claude.ai/code)*',
  '**Generated with [Claude Code](https://claude.com/claude-code)**',
  '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
  '_🤖 Generated with [Claude Code](https://claude.ai/code)_',
  '🤖 _Generated with [Claude Code](https://claude.ai/code)_',
  'Generated with Claude Code',
  'Generated by Claude Code.',
  '_Generated by Claude Code._',
  '_Generated by [Claude Code](https://claude.ai/code)_.',
  '  Generated with [Claude Code](https://claude.ai/code)  ',
  'generated with claude code',
];

test('every real footer variant is removed', () => {
  for (const footer of FOOTERS) {
    assert.equal(cleaned(`Done: the tests pass.\n\n${footer}`), 'Done: the tests pass.', footer);
    assert.equal(cleaned(`Done: the tests pass.\n\n${footer}\n`), 'Done: the tests pass.', `${footer} + newline`);
    assert.equal(cleaned(`Done.\r\n\r\n${footer}\r\n`), 'Done.', `${footer} with CRLF`);
  }
});

test('the usual separator stays; only the footer line goes', () => {
  assert.equal(cleaned('Done.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'), 'Done.\n\n---');
});

test('a footer in the middle is removed and the lines around it are kept', () => {
  assert.equal(cleaned('First.\nGenerated with Claude Code\nLast.'), 'First.\nLast.');
});

test('a sentence that only mentions Claude Code is kept', () => {
  for (const body of [
    'I used Claude Code for this change.',
    'This summary was generated by Claude Code and checked by hand.',
    'Generated by Claude Code, then edited.',
    'Generated by Claude Code and reviewed',
    'Not generated with Claude Code',
    '> Generated with Claude Code',
    '- Generated with Claude Code',
    'Generated by [Claude Code](https://claude.ai/code) for issue 4',
    'Generated with Claude',
    'Generated by Copilot',
  ]) {
    assert.equal(cleaned(`Note.\n\n${body}`), null, body);
  }
});

test('a Co-Authored-By line is kept', () => {
  for (const body of ['Co-Authored-By: Claude <noreply@anthropic.com>', 'Co-authored-by: Claude Opus <noreply@anthropic.com>']) {
    assert.equal(cleaned(`Commit text.\n\n${body}`), null, body);
    assert.equal(cleaned(`Commit text.\n\n${body}\n\nGenerated with Claude Code`), `Commit text.\n\n${body}`, `${body} + footer`);
  }
});

test('the rest of the body is unchanged byte for byte apart from trailing blank lines', () => {
  const rest = [
    '## Résumé ✅\t',
    '',
    'Line with two trailing spaces  ',
    '\tTabbed line\r',
    '```bash',
    'echo "$HOME" `date` \\n %s',
    '```',
    '',
    '',
    '',
    '| a | b |',
    '* not *emphasis* Generated with Claude Code here',
    '---',
  ].join('\n');
  assert.equal(cleaned(`${rest}\n_Generated by [Claude Code](https://claude.ai/code)_\n\n  \n`), rest);
  assert.equal(cleaned(`${rest}\n\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)`), rest);
});

test('a body without a footer is not touched', () => {
  const r = run({ body: 'Plain text.\n\n\n' });
  assert.equal(r.code, 0, r.out);
  assert.equal(r.args, null, 'no API call');
  assert.match(r.out, /no AI footer/);
  assert.equal(run({ body: '' }).args, null, 'an empty body needs no call');
});

test('only the maintainer account is edited', () => {
  for (const author of ['someone', 'pacocartones-bot', '']) {
    const r = run({ body: 'Hi.\n\nGenerated with Claude Code', author });
    assert.equal(r.code, 0, r.out);
    assert.equal(r.args, null, `author ${JSON.stringify(author)}`);
  }
});

test('each event is written back to its own endpoint, with a notice and a summary line', () => {
  const cases = {
    issues: ['repos/pacocartones/repo/issues/7', '7', 'https://github.com/pacocartones/repo/issues/7'],
    issue_comment: ['repos/pacocartones/repo/issues/comments/101', '101', 'https://github.com/pacocartones/repo/issues/7#issuecomment-101'],
    pull_request_review_comment: ['repos/pacocartones/repo/pulls/comments/202', '202', 'https://github.com/pacocartones/repo/pull/8#discussion_r202'],
    pull_request_review: ['repos/pacocartones/repo/pulls/8/reviews/303', '303', 'https://github.com/pacocartones/repo/pull/8#pullrequestreview-303'],
  };
  for (const [event, [endpoint, id, url]] of Object.entries(cases)) {
    const r = run({ event, body: `Text of ${event}.\n\n_Generated by [Claude Code](https://claude.ai/code)_` });
    assert.equal(r.code, 0, r.out);
    // GitHub updates a review with PUT; issues and comments with PATCH.
    const method = r.args.indexOf('-X');
    assert.equal(r.args[method + 1], event === 'pull_request_review' ? 'PUT' : 'PATCH', `${event}: ${r.args}`);
    assert.ok(r.args.includes(endpoint), `${event}: ${r.args}`);
    assert.deepEqual(r.payload, { body: `Text of ${event}.` }, event);
    assert.match(r.out, new RegExp(`::notice::.*${event}.*${id}.*${url.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), event);
    assert.ok(r.summary.includes(event) && r.summary.includes(id) && r.summary.includes(url), `${event} summary: ${r.summary}`);
  }
});

test('the event body is read from its own variable, not from another event field', () => {
  // On issue_comment the issue body is also set; only the comment is edited.
  const r = run({ event: 'issue_comment', body: 'No footer here.' });
  assert.equal(r.args, null, r.out);
});
